-- Create Users Table
CREATE TABLE USERS (
    USER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    EMAIL VARCHAR2(100) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(100) NOT NULL,
    NAME VARCHAR2(100) NOT NULL,
    ROLE VARCHAR2(20) CHECK (ROLE IN ('ADMIN', 'CUSTOMER')) NOT NULL
);

-- Create User Addresses Table
CREATE TABLE USER_ADDRESSES (
    ADDRESS_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    ADDRESS_LINE VARCHAR2(255) NOT NULL,
    CITY VARCHAR2(100) NOT NULL,
    POSTAL_CODE VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_ADDR_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE
);

-- Create Categories Table
CREATE TABLE CATEGORIES (
    CATEGORY_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CATEGORY_NAME VARCHAR2(100) NOT NULL UNIQUE
);

-- Create Products Table
CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    PRODUCT_NAME VARCHAR2(200) NOT NULL,
    PRODUCT_PRICE NUMBER(10, 2) CHECK (PRODUCT_PRICE >= 0) NOT NULL,
    CATEGORY_ID NUMBER,
    CONSTRAINT FK_PROD_CAT FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORIES(CATEGORY_ID) ON DELETE SET NULL
);

-- Create Product Kits Table (Bundles)
CREATE TABLE PRODUCT_KITS (
    KIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    KIT_NAME VARCHAR2(200) NOT NULL,
    DISCOUNT_PERCENTAGE NUMBER(3, 2) CHECK (DISCOUNT_PERCENTAGE BETWEEN 0 AND 1)
);

CREATE TABLE KIT_ITEMS (
    KIT_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    PRIMARY KEY (KIT_ID, PRODUCT_ID),
    CONSTRAINT FK_KIT_ID FOREIGN KEY (KIT_ID) REFERENCES PRODUCT_KITS(KIT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_KIT_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

-- Create Warehouses Table
CREATE TABLE WAREHOUSES (
    WAREHOUSE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(100) NOT NULL,
    LOCATION VARCHAR2(255) NOT NULL
);

-- Create Inventory Table
CREATE TABLE INVENTORY (
    PRODUCT_ID NUMBER NOT NULL,
    WAREHOUSE_ID NUMBER NOT NULL,
    STOCK_QUANTITY NUMBER CHECK (STOCK_QUANTITY >= 0) NOT NULL,
    PRIMARY KEY (PRODUCT_ID, WAREHOUSE_ID),
    CONSTRAINT FK_INV_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE,
    CONSTRAINT FK_INV_WARE FOREIGN KEY (WAREHOUSE_ID) REFERENCES WAREHOUSES(WAREHOUSE_ID) ON DELETE CASCADE
);

-- Create Discount Codes Table
CREATE TABLE DISCOUNT_CODES (
    DISCOUNT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CODE VARCHAR2(50) NOT NULL UNIQUE,
    DISCOUNT_PERCENTAGE NUMBER(3) CHECK (DISCOUNT_PERCENTAGE BETWEEN 1 AND 100) NOT NULL,
    EXPIRY_DATE TIMESTAMP NOT NULL,
    USAGE_LIMIT NUMBER DEFAULT 0,         -- 0 = unlimited
    TIMES_USED NUMBER DEFAULT 0,
    IS_ACTIVE NUMBER(1) DEFAULT 1 CHECK (IS_ACTIVE IN (0, 1)),
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Create Orders Table
CREATE TABLE ORDERS (
    ORDER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    ADDRESS_ID NUMBER,
    DISCOUNT_CODE VARCHAR2(50),
    ORDER_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ORDER_STATUS VARCHAR2(20) CHECK (ORDER_STATUS IN ('PENDING', 'SHIPPED', 'DELIVERED', 'CANCELLED')) NOT NULL,
    TOTAL_AMOUNT NUMBER(10, 2) NOT NULL,
    CONTACT_NAME VARCHAR2(200),
    CONTACT_PHONE VARCHAR2(50),
    CONTACT_EMAIL VARCHAR2(100),
    PAYMENT_METHOD VARCHAR2(100),
    CONSTRAINT FK_ORD_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE SET NULL,
    CONSTRAINT FK_ORD_ADDR FOREIGN KEY (ADDRESS_ID) REFERENCES USER_ADDRESSES(ADDRESS_ID) ON DELETE SET NULL,
    CONSTRAINT FK_ORD_DISC FOREIGN KEY (DISCOUNT_CODE) REFERENCES DISCOUNT_CODES(CODE) ON DELETE SET NULL
);

-- Create Order Items Table
CREATE TABLE ORDER_ITEMS (
    ORDER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    QUANTITY NUMBER CHECK (QUANTITY > 0) NOT NULL,
    PRICE_AT_PURCHASE NUMBER(10, 2) NOT NULL,
    PRIMARY KEY (ORDER_ID, PRODUCT_ID),
    CONSTRAINT FK_ITEM_ORD FOREIGN KEY (ORDER_ID) REFERENCES ORDERS(ORDER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_ITEM_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE SET NULL
);

-- Create Wishlists Table
CREATE TABLE WISHLISTS (
    USER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    PRIMARY KEY (USER_ID, PRODUCT_ID),
    CONSTRAINT FK_WISH_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_WISH_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

-- Create Reviews Table (SQL part for ratings)
CREATE TABLE REVIEWS_SQL (
    REVIEW_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_ID NUMBER NOT NULL,
    PRODUCT_ID NUMBER NOT NULL,
    RATING NUMBER(1) CHECK (RATING BETWEEN 1 AND 5) NOT NULL,
    REVIEW_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_REV_USER_PROD UNIQUE (USER_ID, PRODUCT_ID),
    CONSTRAINT FK_REV_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID) ON DELETE CASCADE,
    CONSTRAINT FK_REV_PROD FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);
